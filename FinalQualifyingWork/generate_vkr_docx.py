def subheading(text: str) -> str:
    return p(text, bold=True)


def experiment_block(
    *,
    goal: str,
    description: str,
    conditions: list[list[str]] | None = None,
    results: list[list[str]],
    images: list[tuple[str, str]],
    conclusion: str,
) -> list[str]:
    """Единая мини-структура подраздела эксперимента в главе 3."""
    blocks: list[str] = [
        subheading("Цель"),
        p(goal),
        subheading("Описание"),
        p(description),
    ]
    if conditions:
        blocks.append(subheading("Условия и методика"))
        blocks.append(table(conditions))
    blocks.append(subheading("Результаты"))
    blocks.append(table(results))
    for rel_path, caption in images:
        blocks.append(image(rel_path, caption))
    blocks.append(subheading("Выводы"))
    blocks.append(p(conclusion))
    return blocks


def placeholder(text: str) -> str:
    return p(f"[ЗАГЛУШКА: {text}]", italic=True)


def _png_size(path: Path) -> tuple[int, int]:
    with path.open("rb") as f:
        sig = f.read(24)
    if len(sig) >= 24 and sig[:8] == b"\x89PNG\r\n\x1a\n":
        return struct.unpack(">II", sig[16:24])
    return 1200, 700


def image(rel_path: str, caption: str, width_cm: float = 15.0) -> str:
    path = ROOT / rel_path
    if not path.exists():
        return placeholder(f"добавить рисунок: {caption}; файл не найден: {rel_path}")
    rid = f"rIdImg{len(IMAGE_RELS) + 1}"
    target = f"media/image{len(IMAGE_RELS) + 1}.png"
    IMAGE_RELS.append((rid, path, target))
    w_px, h_px = _png_size(path)
    cx = int(width_cm * 360000)
    cy = int(cx * h_px / max(w_px, 1))
    drawing = f'''
<w:p><w:pPr><w:jc w:val="center"/></w:pPr><w:r><w:drawing>
<wp:inline distT="0" distB="0" distL="0" distR="0" xmlns:wp="http://schemas.openxmlformats.org/drawingml/2006/wordprocessingDrawing">
<wp:extent cx="{cx}" cy="{cy}"/>
<wp:docPr id="{len(IMAGE_RELS)}" name="Picture {len(IMAGE_RELS)}"/>
<a:graphic xmlns:a="http://schemas.openxmlformats.org/drawingml/2006/main">
<a:graphicData uri="http://schemas.openxmlformats.org/drawingml/2006/picture">
<pic:pic xmlns:pic="http://schemas.openxmlformats.org/drawingml/2006/picture">
<pic:nvPicPr><pic:cNvPr id="0" name="{esc(path.name)}"/><pic:cNvPicPr/></pic:nvPicPr>
<pic:blipFill><a:blip r:embed="{rid}" xmlns:r="http://schemas.openxmlformats.org/officeDocument/2006/relationships"/><a:stretch><a:fillRect/></a:stretch></pic:blipFill>
<pic:spPr><a:xfrm><a:off x="0" y="0"/><a:ext cx="{cx}" cy="{cy}"/></a:xfrm><a:prstGeom prst="rect"><a:avLst/></a:prstGeom></pic:spPr>
</pic:pic>
</a:graphicData>
</a:graphic>
</wp:inline>
</w:drawing></w:r></w:p>
'''
    return drawing + p(caption)


